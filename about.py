from typing import Dict, Sequence

# ---------------------------------------------------------------------------
# أدوات بناء HTML (مجموعة العلامات المدعومة في QTextBrowser)
# ---------------------------------------------------------------------------
_C: Dict[str, str] = {}


def _h2(anchor: str, text: str) -> str:
    return (f'<a name="{anchor}"></a><h2 style="color:{_C["primary"]}; margin-top:26px; '
            f'border-bottom:1px solid {_C["border"]};">{text}</h2>')


def _h3(text: str) -> str:
    return f'<h3 style="color:{_C["secondary"]}; margin-top:16px;">{text}</h3>'


def _p(text: str) -> str:
    return f"<p>{text}</p>"


def _ul(items: Sequence[str]) -> str:
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def _ol(items: Sequence[str]) -> str:
    return "<ol>" + "".join(f"<li>{i}</li>" for i in items) + "</ol>"


def _k(text: str) -> str:
    """نص اختصار لوحة مفاتيح / قيمة حرفية."""
    return f'<span style="background-color:{_C["surface"]}; color:{_C["text"]};">&nbsp;<code>{text}</code>&nbsp;</span>'


def _tbl(headers: Sequence[str], rows: Sequence[Sequence[str]], widths: Sequence[int] = ()) -> str:
    out = [f'<table width="100%" cellspacing="0" cellpadding="6" border="1" style="border-color:{_C["border"]};">']
    out.append("<tr>")
    for i, h in enumerate(headers):
        w = f' width="{widths[i]}%"' if i < len(widths) else ""
        out.append(f'<th{w} bgcolor="{_C["surface"]}" align="right"><b>{h}</b></th>')
    out.append("</tr>")
    for r in rows:
        out.append("<tr>" + "".join(f'<td align="right" valign="top">{c}</td>' for c in r) + "</tr>")
    out.append("</table>")
    return "".join(out)


def _note(text: str, title: str = "ملاحظة") -> str:
    return (f'<table width="100%" cellspacing="0" cellpadding="8" border="0"><tr>'
            f'<td bgcolor="{_C["surface"]}" style="border-right:4px solid {_C["secondary"]};">'
            f'<b style="color:{_C["secondary"]};">{title}:</b> {text}</td></tr></table>')


def _pre(text: str) -> str:
    return (f'<pre style="background-color:{_C["surface"]}; color:{_C["text"]}; padding:6px;">'
            f'{text}</pre>')


